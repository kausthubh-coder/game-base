// Audit raw earned exports without changing them. bun tools/audit-bench-copper.mjs <run-directory>
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const out=resolve(process.argv[2]);
const hashes={};
const read=name=>{const raw=readFileSync(resolve(out,name+'.save.json'),'utf8');hashes[name]=createHash('sha256').update(raw).digest('hex');return JSON.parse(raw);};
const a=read('middle-bench'),b=read('middle-continued');
for(const key of ['inventory','bench','placeables','settlement','quests'])assert.deepEqual(a.game.systems[key],b.game.systems[key],key);
assert.deepEqual(a.world,b.world,'middle world edits');
const modes=s=>s.game.systems.farms.farms.map(({id,mode,away,best})=>({id,mode,away,best}));
assert.deepEqual(modes(a),modes(b),'middle farm modes');
const pets=s=>s.game.systems.pets.pets.map(({id,trust,bonded})=>({id,trust,bonded}));
assert.deepEqual(pets(a),pets(b),'middle companion identity and bond');
const f=read('earned-copper'),flags=Object.fromEntries(f.game.flags);
assert.equal(flags['quest.bench.done'],true);assert.equal(flags['quest.copper.done'],true);assert.equal(flags['quest.count.started'],true);assert.notEqual(flags['scene.22'],true);
assert.equal(f.game.systems.bench.armor,2);
const count=id=>f.game.systems.inventory.slots.filter(x=>x?.id===id).reduce((n,x)=>n+x.count,0);
assert.equal(count('quill_strip'),0,'placed equipped strip was not consumed');
assert.ok(!f.game.systems.bench.kit.includes('quill_strip'),'consumed kit slot persisted');
assert.equal(count('shed_pelt'),1,'two ordinary visitor gifts minus the copper weapon cost');
assert.ok(f.game.systems.bench.weapons.some(w=>w.weapon==='staff'&&w.tier===2&&w.fitting==='padded_grip'));
for(const id of ['moss','quill','copper']){const farm=f.game.systems.farms.farms.find(v=>v.id===id);assert.equal(farm.mode,'give');assert.equal(farm.away,0);assert.equal(flags['farm.'+id+'.living'],true);}
assert.equal(flags['job.dax'],'watch');assert.equal(flags['settler.hobb'],true);assert.equal(flags['settler.dax'],true);
assert.ok(pets(f).some(p=>p.id==='pet:leaftail:1'&&p.bonded&&p.trust===3));
const take=read('earned-take'),give=read('earned-give');
assert.equal(take.game.systems.farms.farms.find(v=>v.id==='copper').mode,'take');assert.ok(take.game.systems.farms.farms.find(v=>v.id==='copper').away>0);
assert.equal(give.game.systems.farms.farms.find(v=>v.id==='copper').mode,'give');
const replay=JSON.parse(readFileSync(resolve(out,'replay.json'),'utf8'));
const imports=replay.inputs.filter(i=>i.type==='import-earned-pre-choice');assert.equal(imports.length,2);assert.equal(imports[0].sha256,imports[1].sha256);
assert.equal(replay.status,'PASS');
assert.equal(replay.inputHash,'d1de50e2eb48a7de5b9af900e470cabd2a88d6688e2e701a18407db1e2c7290b','requires complete fresh earned route');
read('earned-pre-choice');assert.equal(imports[0].sha256,hashes['earned-pre-choice']);
const combat=replay.inputs.filter(i=>i.type==='combat-observation').map(i=>i.fight);assert.ok(combat.some(f=>f.record.rigsPlaced>=1&&f.record.rigsTriggered>=1),'quill strip never worked');
const dodgeAt=replay.inputs.findIndex(i=>i.type==='copper-grip-dodge');assert.ok(dodgeAt>=0,'copper grip never used');
const beforeDodge=replay.inputs.slice(0,dodgeAt).filter(i=>i.type==='combat-observation').at(-1).fight.record.dodges;
assert.ok(replay.inputs.slice(dodgeAt+1).some(i=>i.type==='combat-observation'&&i.fight.record.dodges>beforeDodge),'dodge input did not register');
assert.equal(f.game.systems.crops.crops.filter(c=>c[3]==='carrot').length,8);
assert.equal(f.game.systems.farms.farms.find(v=>v.id==='copper').best,4);
const result={status:'PASS',source:replay.sha,hashes,flags,limits:'Local raw-save audit. Read the replay for input and waiting provenance.'};writeFileSync(resolve(out,'audit.json'),JSON.stringify(result,null,2));console.log('PASS raw earned copper save audit');
