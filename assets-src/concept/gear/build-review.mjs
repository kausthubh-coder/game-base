// Production formatting only: crop and resize generated paintings, never redraw them.
import sharp from 'sharp';
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = dirname(fileURLToPath(import.meta.url));
const svg = (w,h,body) => Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">${body}</svg>`);
const text = (x,y,s,size=18) => `<text x="${x}" y="${y}" fill="#3b4255" font-family="Georgia" font-size="${size}">${s}</text>`;
const crops = {
  sword: [[365,740,240,240],[680,740,240,240],[990,740,240,240],[1290,740,250,240]],
  bow: [[70,722,160,166],[462,722,160,166],[856,722,160,166],[1230,722,160,166]],
  staff: [[410,813,120,150],[685,813,120,150],[960,813,125,150],[1240,813,130,150]],
  armour: [[385,730,190,225],[695,730,205,225],[1025,730,195,225],[1350,730,210,225]],
  fittings: [[580,348,142,144],[995,348,142,144],[1415,348,142,144],[580,809,142,160],[995,809,142,160],[1415,809,142,160]],
  tools: [[18,530,190,215],[335,530,195,215],[650,530,155,215],[925,530,222,215],[1270,530,210,215]],
};
for (const [name,rects] of Object.entries(crops)) {
  const path = join(dir,`${name}.webp`);
  const original = await readFile(path);
  const top = await sharp(original).extract({left:0,top:0,width:1568,height:1003}).png().toBuffer();
  const layers = [{input:top,left:0,top:0}];
  let labels = text(24,1030,'Native size review: each frame below is exactly 128 × 128 pixels. View at 100%.',20);
  for (let i=0;i<rects.length;i++) {
    const [left,top,width,height]=rects[i];
    const input=await sharp(original).extract({left,top,width,height}).resize(128,128,{fit:'contain',background:'#ece5d8'}).png().toBuffer();
    const x=40+i*250;
    layers.push({input,left:x,top:1045});
    labels+=text(x,1194,`${i+1}. Held study`,15);
  }
  layers.push({input:svg(1600,1210,labels),left:0,top:0});
  await sharp({create:{width:1600,height:1210,channels:3,background:'#ece5d8'}}).composite(layers).webp({quality:88}).toFile(path+'.tmp');
  const {rename}=await import('node:fs/promises'); await rename(path+'.tmp',path);
}

// The icon master is a strict six-column/five-row painting generated by image_gen.
const master = sharp(join(dir,'sources/icons-master.webp'));
const meta=await master.metadata();
const names=['Guild sword','Copper sword','Brass sword','Tusk sword','Guild bow','Copper bow','Spring bow','Tusk bow','Guild staff','Copper staff','Brass staff','Rootwood staff','Canvas jacket','Padded jacket','Quill coat','Root-weave','Quill edge','Padded grip','Spring hilt','Glow cap','Slick sheath','Honey binding','Axe','Hoe','Spade','Watering can','Saw'];
let labels=text(30,38,'Gear inventory study',30)+text(30,67,'27 items • actual 64 px • actual 32 px • 32 px enlarged ×3 with nearest neighbour',18);
const layers=[];
for(let i=0;i<names.length;i++) {
  const col=i%6,row=Math.floor(i/6);
  const left=Math.round(col*meta.width/6), top=Math.round(row*meta.height/5);
  const width=Math.round((col+1)*meta.width/6)-left, height=Math.round((row+1)*meta.height/5)-top;
  const tile=await master.clone().extract({left,top,width,height}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  // Flood only the cream connected to the tile edges. Preserve enclosed ivory and metal.
  const {data,info}=tile; const seen=new Uint8Array(info.width*info.height), queue=[];
  const visit=(x,y)=>{if(x<0||y<0||x>=info.width||y>=info.height)return;const p=y*info.width+x;if(seen[p])return;seen[p]=1;const q=p*4;const [r,g,b]=data.subarray(q,q+3);if(r>160&&g>140&&b>105&&r>=g&&g>=b&&r-b<95){data[q+3]=0;queue.push(p);}};
  for(let x=0;x<info.width;x++){visit(x,0);visit(x,info.height-1);}for(let y=0;y<info.height;y++){visit(0,y);visit(info.width-1,y);}
  for(let q=0;q<queue.length;q++){const p=queue[q],x=p%info.width,y=Math.floor(p/info.width);visit(x-1,y);visit(x+1,y);visit(x,y-1);visit(x,y+1);}
  // Discard tiny fragments of neighbouring cells introduced by the painted grid.
  const marked=new Uint8Array(seen.length),components=[];
  for(let p=0;p<marked.length;p++)if(!marked[p]&&data[p*4+3]){
    const points=[p];marked[p]=1;let sumY=0;
    for(let k=0;k<points.length;k++){
      const a=points[k],x=a%info.width,y=Math.floor(a/info.width);sumY+=y;
      for(const b of [x>0?a-1:-1,x+1<info.width?a+1:-1,y>0?a-info.width:-1,y+1<info.height?a+info.width:-1])if(b>=0&&!marked[b]&&data[b*4+3]){marked[b]=1;points.push(b);}
    }
    components.push({points,meanY:sumY/points.length});
  }
  const largest=Math.max(...components.map(c=>c.points.length));
  for(const c of components)if(c.points.length<largest*.07||c.meanY<info.height*.12||c.meanY>info.height*.95)for(const p of c.points)data[p*4+3]=0;
  const item=await sharp(data,{raw:info}).trim({background:'#00000000',threshold:12}).png().toBuffer();
  const a=await sharp(item).resize(64,64,{fit:'contain',background:'#00000000'}).png().toBuffer();
  const b=await sharp(item).resize(32,32,{fit:'contain',background:'#00000000'}).png().toBuffer();
  const c=await sharp(b).resize(96,96,{kernel:'nearest'}).png().toBuffer();
  const x=30+(i%3)*520,y=95+Math.floor(i/3)*122;
  labels+=text(x,y+20,`${String(i+1).padStart(2,'0')} ${names[i]}`,18);
  for(const [input,dx,dy] of [[a,0,37],[b,92,53],[c,164,27]])layers.push({input,left:x+dx,top:y+dy});
  labels+=`<rect x="${x-4}" y="${y+33}" width="72" height="72" rx="8" fill="#1f2433" stroke="#d3bc8e"/><rect x="${x+88}" y="${y+49}" width="40" height="40" rx="5" fill="#1f2433" stroke="#d3bc8e"/><rect x="${x+160}" y="${y+23}" width="104" height="104" rx="8" fill="#1f2433" stroke="#d3bc8e"/>`;
}
await sharp({create:{width:1600,height:1210,channels:3,background:'#ece5d8'}}).composite([{input:svg(1600,1210,labels),left:0,top:0},...layers]).webp({lossless:true}).toFile(join(dir,'icons.webp'));
